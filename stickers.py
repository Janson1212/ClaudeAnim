"""Writes hooks/stickers.ts: small WebP copies of a few stickers, each wrapped
in an SVG, for the side panel. For the user's own use only (the sticker
licence forbids redistributing modified copies); the originals are untouched."""
import base64, io, sys
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
picks = [('01-hmph-of-course', 'Hmph~ of course'), ('32-did-it', 'Did it!'),
         ('49-leave-it-to-me', 'Leave it to this young lady'), ('107-hehe-table', 'Hehe~'),
         ('166-let-me-think', 'Let me think…'), ('172-yes-maam', "Yes, ma'am!"),
         ('178-crunch-time', 'Crunch time…'), ('23-you-doubt-me', 'You doubt this young lady?')]
S = 220
rows = []
for name, text in picks:
    im = Image.open(f'{src}/{name}.png').convert('RGBA').resize((S * 2, S * 2), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=82, method=6)
    data = base64.b64encode(buf.getvalue()).decode()
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{S}" height="{S}">'
           f'<image width="{S}" height="{S}" href="data:image/webp;base64,{data}"/></svg>')
    rows.append(f"  {{ alt: {('Claude sticker: ' + text)!r}, svg: {svg!r} }},")
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by stickers.py: small copies of a few kelaode stickers for the\n'
            '// side panel. Personal use only; do not share this file.\n\n')
    f.write(f'export const STICKER_SIZE = {S}\n\n')
    f.write('export const STICKERS: readonly { alt: string; svg: string }[] = [\n' + '\n'.join(rows) + '\n]\n')
print('wrote', len(rows), 'stickers, file', sum(len(r) for r in rows), 'chars; largest', max(len(r) for r in rows))
