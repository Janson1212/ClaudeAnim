"""Cuts the white background out of the two animations and writes the mod's
drawing modules (hooks/girl.ts, hooks/runner.ts) with the frames embedded.

Usage: python -I cutout.py <images dir> <out dir for previews> <mod hooks dir>
"""
import base64
import io
import sys

import numpy as np
from PIL import Image
from scipy import ndimage

SRC, OUT, HOOKS = sys.argv[1], sys.argv[2], sys.argv[3]


def cut(rgb: Image.Image) -> Image.Image:
    """White (or near-white) area connected to the edges becomes transparent,
    with the light fringe along the outline faded out and un-whitened."""
    a = np.asarray(rgb.convert('RGB')).astype(np.float32)
    light = a.min(axis=2)
    near_white = light > 232
    # Only the near-white regions that touch the border are background, so
    # white inside the figure (blouse, highlights) stays.
    labels, _ = ndimage.label(near_white)
    edge = np.unique(np.concatenate([labels[0], labels[-1], labels[:, 0], labels[:, -1]]))
    bg = np.isin(labels, edge[edge != 0])
    # Soft edge: in a 2 px band around the background, alpha follows how far
    # the pixel is from white.
    band = ndimage.binary_dilation(bg, iterations=2) & ~bg
    alpha = np.where(bg, 0.0, 1.0)
    fade = np.clip((255.0 - light) / 70.0, 0.0, 1.0)
    alpha = np.where(band, np.minimum(alpha, fade), alpha)
    # Remove the white the fringe was blended with.
    safe = np.maximum(alpha, 1e-3)[..., None]
    color = np.clip((a - (1.0 - alpha[..., None]) * 255.0) / safe, 0, 255)
    out = np.dstack([color, alpha * 255.0]).astype(np.uint8)
    return Image.fromarray(out, 'RGBA')


def webp(im: Image.Image, quality: int) -> bytes:
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=quality, method=6, alpha_quality=90)
    return buf.getvalue()


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode('ascii')


# --- The typing girl: one still picture --------------------------------------
TYPE_H = 128  # shown height in CSS pixels
typing = cut(Image.open(f'{SRC}/9.webp'))
typing = typing.crop(typing.getbbox())
tw, th = typing.size
big = typing.resize((round(tw * 2 * TYPE_H / th), 2 * TYPE_H), Image.LANCZOS)
typing.save(f'{OUT}/typing-cutout.png')
type_bytes = webp(big, 88)
TYPE_W = round(TYPE_H * big.width / big.height)

# --- The runner: eight frames ------------------------------------------------
RUN_H = 22  # the dots row is one line high
gif = Image.open(f'{SRC}/8.gif')
frames, durations = [], []
for i in range(gif.n_frames):
    gif.seek(i)
    frames.append(cut(gif.convert('RGB')))
    durations.append(gif.info.get('duration', 110) or 110)
box = frames[0].getbbox()
for f in frames[1:]:
    b = f.getbbox()
    box = (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
frames = [f.crop(box) for f in frames]
fw, fh = frames[0].size
RUN_PX_H = RUN_H * 3  # a little extra resolution for high-DPI screens
small = [f.resize((round(fw * RUN_PX_H / fh), RUN_PX_H), Image.LANCZOS) for f in frames]
RUN_W = round(RUN_H * fw / fh)
frames[0].save(f'{OUT}/running-cutout.gif', save_all=True, append_images=frames[1:],
               duration=durations, loop=0, disposal=2)
run_bytes = [webp(f, 85) for f in small]
total = sum(durations) / 1000.0
n = len(small)

# --- Write the modules -------------------------------------------------------
girl_svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TYPE_W} {TYPE_H}" '
    f'width="{TYPE_W}" height="{TYPE_H}">'
    # The picture is a still, so she breathes: a slow, slight bob.
    f'<g><animateTransform attributeName="transform" type="translate" '
    f'values="0 0;0 -1.2;0 0" dur="2.4s" repeatCount="indefinite"/>'
    f'<image width="{TYPE_W}" height="{TYPE_H}" href="data:image/webp;base64,{b64(type_bytes)}"/>'
    f'</g></svg>'
)

keys = ';'.join(f'{i / n:.4f}' for i in range(n))
run_parts = []
for i, data in enumerate(run_bytes):
    values = ';'.join('inline' if j == i else 'none' for j in range(n))
    run_parts.append(
        f'<image width="{RUN_W}" height="{RUN_H}" display="{"inline" if i == 0 else "none"}" '
        f'href="data:image/webp;base64,{b64(data)}">'
        f'<animate attributeName="display" values="{values}" keyTimes="{keys}" '
        f'calcMode="discrete" dur="{total:.2f}s" repeatCount="indefinite"/></image>'
    )
run_svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {RUN_W} {RUN_H}" '
    f'width="{RUN_W}" height="{RUN_H}">' + ''.join(run_parts) + '</svg>'
)

HEADER = (
    '// Generated by cutout.py from the picture the user supplied: the white\n'
    '// background is cut out and the frames are embedded as WebP, so the\n'
    '// drawing needs no outside file. Edit the source picture and run it again\n'
    '// rather than editing this file.\n\n'
)
with open(f'{HOOKS}/girl.ts', 'w', encoding='utf-8', newline='\n') as fh_:
    fh_.write(HEADER)
    fh_.write(f'export const GIRL_HEIGHT = {TYPE_H}\nexport const GIRL_WIDTH = {TYPE_W}\n\n')
    fh_.write("export const GIRL_ALT =\n  'An anime girl with long orange hair typing on her laptop at a desk'\n\n")
    fh_.write(f'export const GIRL_SVG = {girl_svg!r}\n'.replace("export const GIRL_SVG = '", "export const GIRL_SVG =\n  '"))
with open(f'{HOOKS}/runner.ts', 'w', encoding='utf-8', newline='\n') as fh_:
    fh_.write(HEADER)
    fh_.write(f'export const RUNNER_HEIGHT = {RUN_H}\nexport const RUNNER_WIDTH = {RUN_W}\n\n')
    fh_.write("export const RUNNER_ALT = 'A tiny girl with long orange hair running'\n\n")
    fh_.write(f'export const RUNNER_SVG = {run_svg!r}\n'.replace("export const RUNNER_SVG = '", "export const RUNNER_SVG =\n  '"))

print(f'typing: {TYPE_W}x{TYPE_H} shown, {len(type_bytes)} bytes, svg {len(girl_svg)} chars')
print(f'runner: {RUN_W}x{RUN_H} shown, {n} frames, {sum(map(len, run_bytes))} bytes, '
      f'{total:.2f}s loop, svg {len(run_svg)} chars')
